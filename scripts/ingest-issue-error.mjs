#!/usr/bin/env node

/**
 * WhatsApp DevTools - GitHub Issue Error Ingestion Parser
 *
 * Usage:
 *   node scripts/ingest-issue-error.mjs --verify --file=issue.md
 *   node scripts/ingest-issue-error.mjs --apply --file=issue.md
 *   node scripts/ingest-issue-error.mjs --verify (reads from process.env.ISSUE_BODY)
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const DATA_FILE = path.resolve(__dirname, '../src/data/whatsapp-errors.json');

const PROVIDER_NAMES = {
  meta: 'Meta WhatsApp 官方',
  aliyun: '阿里云 ChatApp',
  twilio: 'Twilio',
  other: '其他三方服务商',
};

const CATEGORY_NAMES = {
  template: '消息模板与管理',
  messaging: '消息发送与接收',
  rate_limit: '频率与流控限制',
  account: '商业账号与状态',
  authentication: '身份鉴权与Token',
  registration: '号码注册与绑定',
  media: '多媒体处理',
  general: '通用与网关服务',
};

/**
 * Extract content under a specific markdown ### header
 */
function extractSection(markdown, headerPattern) {
  const regex = new RegExp(`###\\s+${headerPattern}[\\r\\n]+([\\s\\S]*?)(?=(?:###\\s+|$))`, 'i');
  const match = markdown.match(regex);
  if (!match) return '';
  return match[1].trim();
}

/**
 * Clean up code blocks from markdown (e.g. ```json ... ```)
 */
function stripCodeBlock(text) {
  if (!text) return '';
  const match = text.match(/```(?:json)?\s*([\s\S]*?)\s*```/);
  return match ? match[1].trim() : text.trim();
}

/**
 * Parse structured markdown generated by GitHub Issue Forms
 */
export function parseIssueMarkdown(markdown) {
  if (!markdown || typeof markdown !== 'string') {
    throw new Error('Issue 内容为空或非文本格式');
  }

  // 1. Provider
  const rawProvider = extractSection(markdown, '服务商渠道.*');
  let provider = 'meta';
  if (/aliyun/i.test(rawProvider)) provider = 'aliyun';
  else if (/twilio/i.test(rawProvider)) provider = 'twilio';
  else if (/other/i.test(rawProvider)) provider = 'other';
  else if (/meta/i.test(rawProvider)) provider = 'meta';

  // 2. Code
  const rawCode = extractSection(markdown, '错误代码.*');
  if (!rawCode) {
    throw new Error('缺少必填字段：错误代码 (Error Code)');
  }
  // If numeric string, convert to Number, otherwise keep string
  const code = /^\d+$/.test(rawCode) ? parseInt(rawCode, 10) : rawCode.trim();

  // 3. Severity
  const rawSeverity = extractSection(markdown, '严重级别.*');
  let severity = 'client_error';
  if (/blocker/i.test(rawSeverity)) severity = 'blocker';
  else if (/rate_limit/i.test(rawSeverity)) severity = 'rate_limit';
  else if (/service_unavailable/i.test(rawSeverity)) severity = 'service_unavailable';
  else if (/client_error/i.test(rawSeverity)) severity = 'client_error';

  // 4. Category
  const rawCategory = extractSection(markdown, '业务分类.*');
  let category = 'general';
  for (const catKey of Object.keys(CATEGORY_NAMES)) {
    if (new RegExp(catKey, 'i').test(rawCategory)) {
      category = catKey;
      break;
    }
  }

  // 5. Title Zh & En
  const titleZh = extractSection(markdown, '中文错误简述.*');
  if (!titleZh) throw new Error('缺少必填字段：中文错误简述 (Title Zh)');

  const titleEn = extractSection(markdown, '英文官方定义.*') || titleZh;

  // 6. Details Zh
  const detailsZh = extractSection(markdown, '触发原因深度剖析.*');
  if (!detailsZh) throw new Error('缺少必填字段：触发原因深度剖析 (Details Zh)');

  // 7. Solution Zh
  const solutionZh = extractSection(markdown, '排查与解决步骤清单.*');
  if (!solutionZh) throw new Error('缺少必填字段：排查与解决步骤清单 (Solution Zh)');

  // 8. Optional fields
  const rawHttpStatus = extractSection(markdown, 'HTTP 响应状态码.*');
  const httpStatus = rawHttpStatus && /^\d+$/.test(rawHttpStatus) ? parseInt(rawHttpStatus, 10) : undefined;

  const rawPayload = extractSection(markdown, '真实错误报文示例.*');
  const examplePayload = stripCodeBlock(rawPayload);

  const docUrl = extractSection(markdown, '官方文档或工单链接.*') || undefined;
  const contributor = extractSection(markdown, '贡献者署名.*') || undefined;

  const item = {
    code,
    provider,
    providerNameZh: PROVIDER_NAMES[provider] || PROVIDER_NAMES.other,
    category,
    categoryNameZh: CATEGORY_NAMES[category] || '常规与网关',
    titleEn,
    titleZh,
    detailsZh,
    solutionZh,
    severity,
    ...(httpStatus ? { httpStatus } : {}),
    ...(docUrl ? { docUrl } : {}),
    ...(examplePayload ? { examplePayload } : {}),
    ...(contributor ? { contributor } : {}),
  };

  return item;
}

/**
 * Validate and optionally apply the parsed item into whatsapp-errors.json
 */
export function ingestError(markdown, options = { apply: false }) {
  const item = parseIssueMarkdown(markdown);

  if (!fs.existsSync(DATA_FILE)) {
    throw new Error(`数据源文件不存在：${DATA_FILE}`);
  }

  const fileContent = fs.readFileSync(DATA_FILE, 'utf-8');
  const dataset = JSON.parse(fileContent);

  const existingIdx = dataset.items.findIndex(
    (i) => String(i.code).toLowerCase() === String(item.code).toLowerCase() && i.provider === item.provider
  );

  const isUpdate = existingIdx >= 0;

  if (options.apply) {
    if (isUpdate) {
      dataset.items[existingIdx] = {
        ...dataset.items[existingIdx],
        ...item,
      };
      console.log(`[INGEST] 更新已存在错误代码：[${item.provider}] #${item.code}`);
    } else {
      dataset.items.push(item);
      console.log(`[INGEST] 追加全新错误代码：[${item.provider}] #${item.code}`);
    }

    dataset.totalCount = dataset.items.length;
    dataset.lastSyncedAt = new Date().toISOString();

    fs.writeFileSync(DATA_FILE, JSON.stringify(dataset, null, 2) + '\n', 'utf-8');
    console.log(`[INGEST] 数据源写入成功！当前总数：${dataset.totalCount}`);
  }

  return {
    valid: true,
    isUpdate,
    item,
  };
}

// CLI execution
if (process.argv[1] && process.argv[1].endsWith('ingest-issue-error.mjs')) {
  try {
    const args = process.argv.slice(2);
    const isApply = args.includes('--apply');
    let markdown = process.env.ISSUE_BODY || '';

    const fileArg = args.find((a) => a.startsWith('--file='));
    if (fileArg) {
      const filePath = fileArg.split('=')[1];
      markdown = fs.readFileSync(path.resolve(process.cwd(), filePath), 'utf-8');
    }

    if (!markdown) {
      console.error('[ERROR] 未提供 Issue 内容（请通过 --file=... 或环境变量 ISSUE_BODY 传入）');
      process.exit(1);
    }

    const result = ingestError(markdown, { apply: isApply });
    console.log('\n--- 校验通过预览 JSON ---');
    console.log(JSON.stringify(result.item, null, 2));

    if (!isApply) {
      console.log('\n[INFO] 当前为校验模式 (--verify)，未修改本地文件。若需应用请增加 --apply 参数。');
    }
  } catch (err) {
    console.error('[VALIDATION FAILED]', err.message);
    process.exit(1);
  }
}
